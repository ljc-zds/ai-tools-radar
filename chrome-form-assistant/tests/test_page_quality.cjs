const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../extension/link-risk.js'),'utf8')+';globalThis.q=PageQuality;',context);
const q=context.q;
const sample={qualitySample:{title:'Gardening guide',article:'A detailed gardening guide. '.repeat(30),comments:[{text:'Buy cheap unrelated loans here'},{text:'Buy cheap unrelated loans here again'},{text:'Thank you for the helpful soil advice.'}]}};
assert.equal(q.assess({},null).level,'unknown');
assert.equal(q.assess(sample,null).level,'unknown');
assert.equal(q.assess(sample,{level:'high',signals:[{type:'unrelated_promotion',quote:'invented evidence'}]}).level,'unknown');
assert.equal(q.assess(sample,{level:'high',signals:[{type:'unrelated_promotion',quote:'Buy cheap unrelated loans here'}]}).level,'review');
const model={level:'high',reason:'评论中有重复的无关贷款推广。',signals:[{type:'unrelated_promotion',quote:'Buy cheap unrelated loans here'},{type:'repeated_comments',quote:'Buy cheap unrelated loans here again'}]};
const result=q.assess(sample,model);
assert.equal(result.level,'high');assert.equal(result.source,'local_page_codex');
assert.equal(q.matches({state:'done',quality:result},'exclude'),false);
assert.equal(q.matches({state:'failed',quality:result},'unknown'),true);
assert.equal(q.assess(sample,{level:'low',signals:[]}).level,'low');
assert.equal(q.assess({qualitySample:{...sample.qualitySample,comments:[]}},{level:'low',signals:[]}).level,'unknown');
assert.equal(q.assess(sample,{level:'low',signals:model.signals}).level,'review');
assert.equal(q.assess(sample,{level:'high',signals:[{type:'malware',quote:'Buy cheap unrelated loans here'}]}).level,'unknown');
assert.equal(q.level({verdict:'likely_guest',state:'done'}),'unknown');
assert.equal(q.level({verdict:'login_required',state:'done',quality:result}),'high');
console.log('PASS: page quality evidence guards, unknown legacy results, separate eligibility, filter and malformed model output');

vm.runInContext('globalThis.topics=ResourceTopics;',context);
const topics=context.topics;
assert.deepEqual(Array.from(topics.normalize(['美食','新闻','美食','<script>','科技','生活'])),['美食','新闻','科技']);
assert.equal(topics.matches({},'unknown'),true);
assert.equal(topics.matches({topics:['美食','生活']},'美食'),true);
assert.equal(topics.matches({topics:['美食','生活']},'游戏'),false);
assert.equal(topics.matches({topics:'美食'},'unknown'),true);
assert.equal(topics.matches({topics:['新闻']},'all'),true);
console.log('PASS: topic normalization, deduplication, bounded tags and legacy unknown filtering');
